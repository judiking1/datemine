#!/usr/bin/env node
/**
 * Generate an app-importable preview of the (anonymized) draft cards so the owner can
 * review them inside the app in "검수 모드". Output carries NO reviewedAt, so isPublishable()
 * stays false and the app can badge these as 미발행. Real names/sources never enter here —
 * drafts are Layer 2 (anonymized); this only mirrors what data/drafts already holds.
 *
 * Usage: node scripts/build-draft-preview.mjs
 *   → writes apps/mobile/src/data/draftsPreview.generated.ts
 */
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const DRAFTS_DIR = join(ROOT, "data", "drafts");
const OUT = join(ROOT, "apps", "mobile", "src", "data", "draftsPreview.generated.ts");

const drafts = readdirSync(DRAFTS_DIR)
  .filter((n) => n.endsWith(".json"))
  .sort()
  .map((n) => JSON.parse(readFileSync(join(DRAFTS_DIR, n), "utf8")));

const byMonthDay = {};
const byLunarKey = {};
for (const d of drafts) {
  if (typeof d.key === "string" && d.key.startsWith("lunar:")) {
    byLunarKey[d.key.slice("lunar:".length)] = d.card;
  } else {
    byMonthDay[d.key] = d.card;
  }
}

const header = `// AUTO-GENERATED by scripts/build-draft-preview.mjs — do not edit by hand.
// Anonymized draft cards (Layer 2) for in-app 검수 모드. No reviewedAt => 미발행.
import type { DailyContext } from "@datemine/domain";

type DraftCard = Omit<DailyContext, "date">;

`;

const body =
  `export const draftCardsByMonthDay: Readonly<Record<string, DraftCard>> = ${JSON.stringify(byMonthDay, null, 2)};\n\n` +
  `export const draftCardsByLunarKey: Readonly<Record<string, DraftCard>> = ${JSON.stringify(byLunarKey, null, 2)};\n`;

writeFileSync(OUT, header + body);
console.log(
  `Wrote ${OUT}\n  ${Object.keys(byMonthDay).length} fixed + ${Object.keys(byLunarKey).length} lunar draft cards.`,
);
